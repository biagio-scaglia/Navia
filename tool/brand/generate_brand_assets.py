"""Generates Navia's logo and Android launcher icons from one geometry.

The mark is a blue-to-aqua disc with a white arrowhead heading north-east and
a small origin ring: "from here to there".

Usage (from the repository root, requires Pillow):

    python tool/brand/generate_brand_assets.py
"""

import math
import os

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

BRAND = (0x16, 0x77, 0xFF)
AQUA = (0x00, 0xBF, 0xA6)
WHITE = (0xFF, 0xFF, 0xFF)

# Geometry in a unit space: disc centered at (0, 0) with radius 1.
_ARROW_UP = [(0.0, -0.60), (0.40, 0.42), (0.0, 0.20), (-0.40, 0.42)]
_ARROW_ANGLE = math.radians(45)
_ARROW_OFFSET = (0.07, -0.07)
ORIGIN_CENTER = (-0.46, 0.46)
ORIGIN_RADIUS = 0.12
ORIGIN_STROKE = 0.075
ARROW_ROUNDING = 0.07
# Dots tracing the way from the origin ring to the arrow.
ROUTE_DOTS = [(-0.28, 0.28), (-0.17, 0.17)]
ROUTE_DOT_RADIUS = 0.04


def arrow():
    cos, sin = math.cos(_ARROW_ANGLE), math.sin(_ARROW_ANGLE)
    ox, oy = _ARROW_OFFSET
    return [(x * cos - y * sin + ox, x * sin + y * cos + oy) for x, y in _ARROW_UP]


def _map(points, center, radius):
    cx, cy = center
    return [(cx + x * radius, cy + y * radius) for x, y in points]


def _fmt(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


def _path(points):
    head, *tail = points
    return "M" + " L".join(f"{_fmt(x)} {_fmt(y)}" for x, y in [head, *tail]) + "Z"


def logo_svg(size=48):
    r = size / 2
    arrow_path = _path(_map(arrow(), (r, r), r))
    ox, oy = _map([ORIGIN_CENTER], (r, r), r)[0]
    dots = "\n".join(
        f'  <circle cx="{_fmt(x)}" cy="{_fmt(y)}" r="{_fmt(ROUTE_DOT_RADIUS * r)}" fill="#FFFFFF"/>'
        for x, y in _map(ROUTE_DOTS, (r, r), r)
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">
  <defs>
    <linearGradient id="disc" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#1677FF"/>
      <stop offset="1" stop-color="#00BFA6"/>
    </linearGradient>
    <linearGradient id="gloss" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.35"/>
      <stop offset="0.5" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
  </defs>
  <circle cx="{_fmt(r)}" cy="{_fmt(r)}" r="{_fmt(r)}" fill="url(#disc)"/>
  <circle cx="{_fmt(r)}" cy="{_fmt(r)}" r="{_fmt(r)}" fill="url(#gloss)"/>
  <path d="{arrow_path}" fill="#FFFFFF" stroke="#FFFFFF" stroke-width="{_fmt(ARROW_ROUNDING * r)}" stroke-linejoin="round"/>
  <circle cx="{_fmt(ox)}" cy="{_fmt(oy)}" r="{_fmt(ORIGIN_RADIUS * r)}" fill="none" stroke="#FFFFFF" stroke-width="{_fmt(ORIGIN_STROKE * r)}"/>
{dots}
</svg>
"""


def adaptive_foreground_xml():
    # 108dp canvas; the launcher mask keeps a 66dp circle, radius 33.
    center, radius = (54, 54), 30
    arrow_path = _path(_map(arrow(), center, radius))
    ox, oy = _map([ORIGIN_CENTER], center, radius)[0]
    ring_r = ORIGIN_RADIUS * radius
    ring = (
        f"M{_fmt(ox - ring_r)} {_fmt(oy)}"
        f" a{_fmt(ring_r)} {_fmt(ring_r)} 0 1 0 {_fmt(2 * ring_r)} 0"
        f" a{_fmt(ring_r)} {_fmt(ring_r)} 0 1 0 {_fmt(-2 * ring_r)} 0"
    )
    dot_r = ROUTE_DOT_RADIUS * radius
    dots = "".join(
        f"M{_fmt(x - dot_r)} {_fmt(y)}"
        f" a{_fmt(dot_r)} {_fmt(dot_r)} 0 1 0 {_fmt(2 * dot_r)} 0"
        f" a{_fmt(dot_r)} {_fmt(dot_r)} 0 1 0 {_fmt(-2 * dot_r)} 0"
        for x, y in _map(ROUTE_DOTS, center, radius)
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_brand_assets.py. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFF"
        android:strokeColor="#FFFFFF"
        android:strokeWidth="{_fmt(ARROW_ROUNDING * radius)}"
        android:strokeLineJoin="round"
        android:pathData="{arrow_path}" />
    <path
        android:strokeColor="#FFFFFF"
        android:strokeWidth="{_fmt(ORIGIN_STROKE * radius)}"
        android:pathData="{ring}" />
    <path
        android:fillColor="#FFFFFF"
        android:pathData="{dots}" />
</vector>
"""


ADAPTIVE_BACKGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_brand_assets.py. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108">
                <item android:offset="0" android:color="#FF1677FF" />
                <item android:offset="1" android:color="#FF00BFA6" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""

ADAPTIVE_ICON_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_brand_assets.py. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""


def render_png(size):
    """Round legacy launcher icon (API < 26), supersampled for smooth edges."""
    scale = 4
    s = size * scale
    r = s / 2

    # Diagonal gradient, clipped to a disc.
    gradient = Image.new("RGB", (s, s))
    pixels = gradient.load()
    for y in range(s):
        for x in range(s):
            t = (x + y) / (2 * (s - 1))
            pixels[x, y] = tuple(round(a + (b - a) * t) for a, b in zip(BRAND, AQUA))
    mask = Image.new("L", (s, s), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, s - 1, s - 1), fill=255)
    image = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    image.paste(gradient, (0, 0), mask)

    # Soft top gloss.
    gloss = Image.new("L", (s, s), 0)
    gloss_pixels = gloss.load()
    for y in range(s // 2):
        alpha = round(90 * (1 - y / (s / 2)))
        for x in range(s):
            gloss_pixels[x, y] = alpha
    gloss = Image.composite(gloss, Image.new("L", (s, s), 0), mask)
    image.paste(Image.new("RGBA", (s, s), WHITE + (255,)), (0, 0), gloss)

    draw = ImageDraw.Draw(image)
    points = _map(arrow(), (r, r), r * 0.92)
    draw.polygon(points, fill=WHITE)
    # Closing over two points makes every corner a rounded joint.
    draw.line(points + points[:2], fill=WHITE, width=round(ARROW_ROUNDING * r), joint="curve")
    ox, oy = _map([ORIGIN_CENTER], (r, r), r * 0.92)[0]
    ring_r = ORIGIN_RADIUS * r * 0.92
    draw.ellipse(
        (ox - ring_r, oy - ring_r, ox + ring_r, oy + ring_r),
        outline=WHITE,
        width=round(ORIGIN_STROKE * r * 0.92),
    )
    dot_r = ROUTE_DOT_RADIUS * r * 0.92
    for x, y in _map(ROUTE_DOTS, (r, r), r * 0.92):
        draw.ellipse((x - dot_r, y - dot_r, x + dot_r, y + dot_r), fill=WHITE)
    return image.resize((size, size), Image.LANCZOS)


def _write(relative, content):
    path = os.path.join(ROOT, relative)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as file:
        file.write(content)


def main():
    _write("assets/brand/navia_logo.svg", logo_svg())
    res = "android/app/src/main/res"
    _write(f"{res}/drawable/ic_launcher_foreground.xml", adaptive_foreground_xml())
    _write(f"{res}/drawable/ic_launcher_background.xml", ADAPTIVE_BACKGROUND_XML)
    _write(f"{res}/mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE_ICON_XML)
    densities = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for density, size in densities.items():
        render_png(size).save(os.path.join(ROOT, res, f"mipmap-{density}", "ic_launcher.png"))
    render_png(512).save(os.path.join(ROOT, "assets/brand/navia_logo_512.png"))


if __name__ == "__main__":
    main()
